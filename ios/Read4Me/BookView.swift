import SwiftUI

struct BookView: View {
    let id: UUID
    @ObservedObject var library: LibraryStore
    @ObservedObject var converter: ConversionController
    @ObservedObject var player: PlayerController
    @ObservedObject var apiKeys: APIKeyStore
    @State private var showingSettings = false
    @State private var confirmingRecreation = false
    @State private var configuration = SpeechConfiguration()
    @State private var draft = ""
    @State private var showingText = false

    var body: some View {
        if let book = library.book(id) {
            ScrollView {
                VStack(alignment: .leading, spacing: 24) {
                    Image(systemName: "waveform.circle.fill")
                        .font(.system(size: 80)).foregroundStyle(.indigo)
                        .frame(maxWidth: .infinity).padding(.top, 24)
                    Text(book.title).font(.largeTitle.bold())
                    Label("Stored on this iPhone", systemImage: "internaldrive").foregroundStyle(.secondary)
                    if book.isReady {
                        PlayerView(id: id, player: player)
                        if book.speechConfiguration == nil { recreationButton }
                    } else {
                        conversionSection(book)
                    }
                    Button("Preview extracted text", systemImage: "doc.text") {
                        draft = book.text
                        showingText = true
                    }
                    Text("Narration is AI-generated by OpenAI using your API key. Creating audio sends this text to OpenAI and uses API credits. Saved audio plays offline.")
                        .font(.footnote).foregroundStyle(.secondary)
                }.padding(24)
            }
            .navigationTitle("Audiobook").navigationBarTitleDisplayMode(.inline)
            .sheet(isPresented: $showingSettings) { SettingsView(apiKeys: apiKeys) }
            .confirmationDialog("Replace the previous narration with OpenAI audio?", isPresented: $confirmingRecreation,
                                titleVisibility: .visible) {
                Button("Recreate with OpenAI", role: .destructive) {
                    if player.bookID == id { player.clear() }
                    Task { await converter.recreate(id, configuration: configuration) }
                }
            } message: { Text("The PDF and text stay saved. Previous audio and playback position will be replaced. This uses API credits.") }
            .sheet(isPresented: $showingText) {
                NavigationStack {
                    TextEditor(text: $draft).padding()
                        .disabled(!book.chunks.isEmpty)
                        .navigationTitle("Extracted text")
                        .toolbar {
                            Button("Done") {
                                guard book.chunks.isEmpty else { showingText = false; return }
                                guard !draft.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
                                    library.error = "Add some text before saving."
                                    return
                                }
                                var updated = book
                                updated.text = draft
                                do { try library.update(updated); showingText = false }
                                catch { library.error = error.localizedDescription }
                            }
                        }
                }
            }
        }
    }

    private func conversionSection(_ book: Book) -> some View {
        VStack(alignment: .leading, spacing: 16) {
            if book.chunks.isEmpty {
                Picker("Narrator", selection: $configuration.voice) {
                    ForEach(SpeechConfiguration.voices, id: \.self) { voice in
                        Text(voice.capitalized).tag(voice)
                    }
                }
                TextField("Narration instructions", text: $configuration.instructions, axis: .vertical)
                Text("Model: \(configuration.model)").font(.caption).foregroundStyle(.secondary)
            } else {
                ProgressView(value: Double(book.completedCount), total: Double(book.chunks.count))
                Text("\(book.completedCount) of \(book.chunks.count) sections saved")
            }
            if !apiKeys.hasKey {
                Button("Add OpenAI API key", systemImage: "key") { showingSettings = true }
            }
            if let error = book.conversionError {
                Text(error).foregroundStyle(.red)
            }
            if converter.activeID == id {
                if converter.pauseRequested {
                    Text("Finishing this section before pausing…")
                } else {
                    Button("Pause after this section") { converter.requestPause() }
                }
            } else if !book.chunks.isEmpty && book.speechConfiguration == nil {
                recreationButton
            } else {
                Button {
                    Task { await converter.generate(id, configuration: configuration) }
                } label: {
                    if book.chunks.isEmpty { Text("Create audiobook").frame(maxWidth: .infinity) }
                    else { Text("Resume conversion").frame(maxWidth: .infinity) }
                }
                .buttonStyle(.borderedProminent)
                .disabled(converter.activeID != nil || !apiKeys.hasKey)
            }
        }
    }
    private var recreationButton: some View {
        Button("Recreate with OpenAI", systemImage: "arrow.clockwise") {
            if !apiKeys.hasKey { showingSettings = true; return }
            confirmingRecreation = true
        }.disabled(converter.activeID != nil)
    }

}
